# ─────────────────────── validation & duplicate detection ───────────────────────
import re
from collections import Counter

def norm(s):
    s = s.lower().replace("ё", "е")
    s = re.sub(r"[^\wа-я0-9 ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()

STOP = set("что как кто где когда почему чей чья чьи в на и с по за из у о об от до для the a an of to is was did who what where why how does".split())

def toks(s):
    return {w for w in norm(s).split() if w not in STOP and len(w) > 2}

problems = []
for x in Q:
    if len(x["options"]) != 4 or len(set(x["options"])) != 4:
        problems.append(("bad-options", x["id"]))
    if any(not str(o).strip() for o in x["options"]):
        problems.append(("empty-option", x["id"]))
    if x["answer"] != x["options"][0]:
        problems.append(("answer!=opt0", x["id"]))
    if not x["question_en"] or not x["explanation"]:
        problems.append(("missing-meta", x["id"]))

# exact normalized duplicates
seen = {}
for x in Q:
    k = norm(x["question"])
    if k in seen:
        problems.append(("EXACT-DUP", seen[k], x["id"]))
    else:
        seen[k] = x["id"]

# near-duplicates: high token overlap (Jaccard) between question stems
near = []
tk = [(x["id"], toks(x["question"]), x["question"]) for x in Q]
for a in range(len(tk)):
    for b in range(a + 1, len(tk)):
        ia, ta, qa = tk[a]
        ib, tb, qb = tk[b]
        if not ta or not tb:
            continue
        j = len(ta & tb) / len(ta | tb)
        if j >= 0.5:
            near.append((round(j, 2), ia, ib, qa, qb))

